#!/usr/bin/env python3
"""Generate the extracted-Swift qualification harness for the cached-frontier auto-crop repair (r4, base 374c).

Usage: python3 gen_harness.py [workdir] [output.swift]
  workdir defaults to the directory containing this script's ../work (pre/post images live there);
  pass the directory holding Source.swift.new / Source.swift.orig / CropDetector.swift.new / PPController.swift.new.

Extraction rules (Ops compile-RED lessons r2/r3):
- b-side blocks are VERBATIM from the post-patch files. No renames, no substitutions.
- WTCropSamples extraction stops before the `positions` method: positions touches
  CropDetector/TransferProbeAdmission/IPCClient/MPVCommand/playedFallback (runtime collaborators),
  which are NOT part of this bounded helper harness. Pure statics only.
- a-side (prepatch) block is VERBATIM plus EXACTLY ONE word-boundary rename of the four
  function names usable/spread/spreadOrder/plan -> o_* so both enums can coexist.
  Constants are never touched (r2 corrupted `static let sampleCount` into `static let 12`).
- PPController.cropSearchGrowthRestarts is extracted verbatim so the unchanged-cache negative
  control executes the ACTUAL production condition, not a mirror.

Scope label: bounded pure-helper extraction. Passing here is NOT PP async lifecycle acceptance,
NOT a full scanner run, and NOT native playback proof.
"""
import re, sys, os

WORK = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "work")
OUT = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "main.swift")

def span(path, start_pred):
    lines = open(path).read().splitlines(keepends=True)
    i = next(i for i, l in enumerate(lines) if start_pred(l))
    depth = 0
    for j in range(i, len(lines)):
        depth += lines[j].count("{") - lines[j].count("}")
        if depth == 0:
            return "".join(lines[i:j + 1])
    raise SystemExit("unclosed block at line %d in %s" % (i + 1, path))

def enum_pure_prefix(path, marker="    /// Positions for a wt playback path"):
    """The WTCropSamples enum truncated before its runtime-collaborator positions method."""
    block = span(path, lambda l: l.startswith("enum WTCropSamples {"))
    cut = block.index(marker)
    return block[:cut] + "}\n"

NEW = os.path.join(WORK, "Source.swift.new")
ORIG = os.path.join(WORK, "Source.swift.orig")

bounds = span(NEW, lambda l: l.startswith("enum SourcePixelBounds {"))
samples_b = enum_pure_prefix(NEW)
assert "rawFrontierEnd" in samples_b, "r4 rawFrontierEnd must be inside the pure prefix"
samples_a = enum_pure_prefix(ORIG, marker="    /// Positions for a wt playback path")
samples_a = samples_a.replace("enum WTCropSamples {", "enum WTCropSamplesPrepatch {", 1)
for fn in ("usable", "spread", "spreadOrder", "plan"):
    samples_a = re.sub(r"\b%s\b" % fn, "o_" + fn, samples_a)
assert "static let sampleCount = 12" in samples_a, "constants must survive verbatim"
assert "o_spreadOrder(o_spread(" in samples_a and "o_o_" not in samples_a
for bad in ("IPCClient", "TransferProbeAdmission", "MPVCommand", "playedFallback", "CropDetector."):
    assert bad not in samples_b and bad not in samples_a, "runtime collaborator leaked into pure prefix: " + bad

carry = span(NEW, lambda l: "static func carryPlanReusable" in l)
clear = span(NEW, lambda l: "static func progressClearedOnCompletion" in l)
carry = carry.replace("static func carryPlanReusable", "func SourcePixelCropScanner_carryPlanReusable", 1)
clear = clear.replace("static func progressClearedOnCompletion", "func SourcePixelCropScanner_progressClearedOnCompletion", 1)

growth = span(os.path.join(WORK, "PPController.swift.new"), lambda l: "static func cropSearchGrowthRestarts" in l)
growth = growth.replace("static func cropSearchGrowthRestarts", "func PPController_cropSearchGrowthRestarts", 1)

coverage = span(os.path.join(WORK, "CropDetector.swift.new"), lambda l: "static func planProvesCoverage" in l)
coverage = coverage.replace("static func planProvesCoverage", "func CropDetector_planProvesCoverage", 1)

widen_line = None
for l in open(os.path.join(WORK, "CropDetector.swift.new")):
    if "self.automaticWidenLevel = decisive" in l:
        widen_line = l.strip()
        break
assert widen_line, "widen line not found"

header = """import Foundation

// Extracted-Swift qualification harness, frontier repair r4 (base 374c2b9e14bfbf1614091767c83ce4ce3f07bac8).
// GENERATED by gen_harness.py - never hand-edit extracted blocks.
// VERBATIM extractions from the post-patch files: SourcePixelBounds (bounds+consistent), WTCropSamples pure
// prefix (constants..rawFrontierEnd; the runtime-collaborator `positions` method is deliberately excluded),
// SourcePixelCropScanner.carryPlanReusable / .progressClearedOnCompletion, PPController.cropSearchGrowthRestarts.
// WTCropSamplesPrepatch is the a-side 374c preimage with word-boundary o_* function renames only (constants
// verbatim), for manual-parity checks. The widen policy below is generated from the verbatim detect() line.
// SCOPE: bounded pure-helper extraction. A PASS here is NOT PP async lifecycle acceptance, NOT a full scanner
// run, NOT native playback proof. Ops: swiftc -O main.swift -o harness && ./harness. Mutants listed at the end.

"""

widen_func = """// Verbatim widen decision from CropDetector.detect completion:
//   %s
func widenNextLevel(_ level: Int, decisive: Bool, starved: Bool) -> Int {
    (decisive || !starved) ? 0 : level + 1
}
func scanStarved(membersCount: Int, sampled: Int, needSamples: Int) -> Bool {
    if sampled < needSamples { return true }                       // "scan produced no samples" -> starved: true
    return membersCount < 3                                          // "no agreement" -> starved: members.count < SourcePixelBounds.earlyMinCount
}
""" % widen_line

tests = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "harness_tests.swift.frag")).read()

out = header + bounds + "\n" + samples_b + "\n" + samples_a + "\n// Actual pure carry-rule decisions extracted from SourcePixelCropScanner (r3/r4):\n" + carry + "\n" + clear + "\n// Actual pure growth decision extracted from PPController (r4):\n" + growth + "\n// Actual pure coverage-proof decision extracted from CropDetector (r5):\n" + coverage + "\n" + widen_func + tests
open(OUT, "w").write(out)
print("harness generated:", OUT, len(out.splitlines()), "lines")
